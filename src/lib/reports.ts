import type jsPDFType from 'jspdf';
import type { AdminOverviewResponse, PaymentSubmission, SocietySettings } from '../types.ts';

let pdfLibsPromise: Promise<[typeof import('jspdf'), typeof import('jspdf-autotable')]> | null = null;
let xlsxLibPromise: Promise<typeof import('xlsx')> | null = null;

function loadPdfLibs() {
  if (!pdfLibsPromise) {
    pdfLibsPromise = Promise.all([import('jspdf'), import('jspdf-autotable')]);
  }
  return pdfLibsPromise;
}

function loadXlsxLib() {
  if (!xlsxLibPromise) {
    xlsxLibPromise = import('xlsx');
  }
  return xlsxLibPromise;
}

function formatBdtAscii(amount: number): string {
  return `BDT ${new Intl.NumberFormat('en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(Number(amount || 0))}`;
}

export async function downloadReceiptPdf(
  payment: PaymentSubmission,
  settings: SocietySettings
): Promise<void> {
  const [{ default: jsPDF }, { default: autoTable }] = await loadPdfLibs();
  const doc = new jsPDF({ unit: 'pt', format: 'a5' });

  // Navy header bar
  doc.setFillColor(11, 31, 58);
  doc.rect(0, 0, doc.internal.pageSize.getWidth(), 78, 'F');

  // Gold accent strip
  doc.setFillColor(197, 155, 39);
  doc.rect(0, 78, doc.internal.pageSize.getWidth(), 4, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text(settings.societyNameEn, 28, 34);

  doc.setFontSize(9.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(216, 180, 74);
  doc.text('OFFICIAL PAYMENT RECEIPT', 28, 54);

  doc.setTextColor(15, 23, 42);
  doc.setFontSize(10);
  const receiptNo = payment.receiptNumber || payment.id.toUpperCase();
  doc.text(`Receipt No: ${receiptNo}`, 28, 108);
  doc.text(
    `Verified Date: ${payment.verifiedAt ? new Date(payment.verifiedAt).toLocaleDateString('en-GB') : new Date(payment.createdAt).toLocaleDateString('en-GB')}`,
    28,
    124
  );

  autoTable(doc, {
    startY: 142,
    margin: { left: 28, right: 28 },
    theme: 'grid',
    headStyles: { fillColor: [11, 31, 58], textColor: [255, 255, 255], fontSize: 9 },
    bodyStyles: { fontSize: 9.5, textColor: [15, 23, 42] },
    head: [['Field', 'Details']],
    body: [
      ['Member ID', payment.memberId],
      ['Member Name', payment.memberName],
      ['Payment Category', payment.paymentType.replace('_', ' ').toUpperCase()],
      ['Target Month', payment.month],
      ['Payment Method', payment.method.toUpperCase()],
      ['Sender Account', payment.senderAccount],
      ['Transaction ID (TrxID)', payment.transactionId],
      ['Amount Paid', formatBdtAscii(payment.amount)],
      ['Verification Status', payment.status.toUpperCase()],
      ['Verified By', payment.verifiedBy || 'Society Admin'],
    ],
  });

  const finalY = (doc as jsPDFType & { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY || 420;
  doc.setFontSize(8.5);
  doc.setTextColor(100, 116, 139);
  doc.text(
    'This receipt is system-generated by Hello Noakhali Savings and Investment Society.',
    28,
    finalY + 26
  );

  doc.save(`Receipt_${receiptNo}_${payment.memberId}.pdf`);
}

export async function exportSummaryPdf(data: AdminOverviewResponse): Promise<void> {
  const [{ default: jsPDF }, { default: autoTable }] = await loadPdfLibs();
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  doc.setFillColor(11, 31, 58);
  doc.rect(0, 0, doc.internal.pageSize.getWidth(), 72, 'F');
  doc.setFillColor(197, 155, 39);
  doc.rect(0, 72, doc.internal.pageSize.getWidth(), 4, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text(data.settings.societyNameEn, 36, 34);
  doc.setFontSize(10);
  doc.setTextColor(216, 180, 74);
  doc.text(`Financial Summary Report · Generated ${new Date().toLocaleDateString('en-GB')}`, 36, 54);

  autoTable(doc, {
    startY: 96,
    margin: { left: 36, right: 36 },
    headStyles: { fillColor: [11, 31, 58], textColor: [255, 255, 255] },
    head: [['Metric', 'Value']],
    body: [
      ['Total Registered Members', String(data.stats.totalMembers)],
      ['Active Members', String(data.stats.activeMembers)],
      ['Total Society Savings', formatBdtAscii(data.stats.totalSavings)],
      ['Total Verified Deposits', formatBdtAscii(data.stats.totalVerifiedDeposits)],
      ['Pending Verifications', `${data.stats.pendingPaymentsCount} (${formatBdtAscii(data.stats.pendingPaymentsAmount)})`],
      ['Active Investments Capital', formatBdtAscii(data.stats.totalInvested)],
      ['Total Recorded Income', formatBdtAscii(data.stats.totalIncome)],
      ['Total Recorded Expense', formatBdtAscii(data.stats.totalExpense)],
      ['Net Treasury Flow', formatBdtAscii(data.stats.totalIncome - data.stats.totalExpense)],
      ['Outstanding Unpaid Fines', formatBdtAscii(data.stats.unpaidFinesAmount)],
    ],
  });

  doc.save(`HNS_Financial_Summary_${new Date().toISOString().slice(0, 10)}.pdf`);
}

