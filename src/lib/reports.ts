export async function exportExcelWorkbook(
  scope: 'summary' | 'members' | 'payments' | 'ledger',
  data: AdminOverviewResponse
): Promise<void> {
  const XLSX = await loadXlsxLib();
  const wb = XLSX.utils.book_new();

  if (scope === 'summary') {
    const rows = [
      { Metric: 'Total Members', Value: data.stats.totalMembers },
      { Metric: 'Active Members', Value: data.stats.activeMembers },
      { Metric: 'Total Savings (BDT)', Value: data.stats.totalSavings },
      { Metric: 'Verified Deposits (BDT)', Value: data.stats.totalVerifiedDeposits },
      { Metric: 'Pending Payments Count', Value: data.stats.pendingPaymentsCount },
      { Metric: 'Pending Payments Amount (BDT)', Value: data.stats.pendingPaymentsAmount },
      { Metric: 'Active Investments (BDT)', Value: data.stats.totalInvested },
      { Metric: 'Total Income (BDT)', Value: data.stats.totalIncome },
      { Metric: 'Total Expense (BDT)', Value: data.stats.totalExpense },
      { Metric: 'Net Treasury Flow (BDT)', Value: data.stats.totalIncome - data.stats.totalExpense },
      { Metric: 'Unpaid Fines (BDT)', Value: data.stats.unpaidFinesAmount },
    ];
    XLSX.utils.book_append_sheet(wb, XLSX.utils.json_to_sheet(rows), 'Financial Summary');
  }

  if (scope === 'members') {
    const rows = data.members.map((m) => ({
      MemberID: m.memberId,
      Name: m.name,
      Email: m.email,
      Phone: m.phone,
      Address: m.address,
      NID: m.nid,
      MonthlyTargetBDT: m.monthlyTarget,
      TotalSavingsBDT: m.totalSavings,
      Status: m.status,
      JoinedAt: m.joinedAt,
    }));
    XLSX.utils.book_append_sheet(wb, XLSX.utils.json_to_sheet(rows), 'Members');
  }

  if (scope === 'payments') {
    const rows = data.payments.map((p) => ({
      Date: p.createdAt.slice(0, 10),
      MemberID: p.memberId,
      MemberName: p.memberName,
      Type: p.paymentType,
      Month: p.month,
      Method: p.method,
      SenderAccount: p.senderAccount,
      TransactionID: p.transactionId,
      AmountBDT: p.amount,
      Status: p.status,
      ReceiptNumber: p.receiptNumber || '',
    }));
    XLSX.utils.book_append_sheet(wb, XLSX.utils.json_to_sheet(rows), 'Payments');
  }

  if (scope === 'ledger') {
    const rows = data.ledger.map((l) => ({
      Date: l.date,
      Type: l.type,
      Category: l.category,
      Title: l.title,
      AmountBDT: l.amount,
      Description: l.description,
      RecordedBy: l.recordedBy,
    }));
    XLSX.utils.book_append_sheet(wb, XLSX.utils.json_to_sheet(rows), 'Income_Expense');
  }

  XLSX.writeFile(wb, `HNS_${scope}_${new Date().toISOString().slice(0, 10)}.xlsx`);
}
